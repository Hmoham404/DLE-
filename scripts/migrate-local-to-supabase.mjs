import {readFile,writeFile,mkdir,copyFile,rename} from 'node:fs/promises';
import {constants} from 'node:fs';
import {createHash,randomUUID} from 'node:crypto';
import {isDeepStrictEqual} from 'node:util';
import {cloudRuntime} from './cloud-runtime.mjs';

const cloud=await cloudRuntime();
if(!process.env.MYC_STORAGE_NAMESPACE)throw new Error('Use a dedicated namespace; existing cloud records must stay untouched.');
const sha=value=>createHash('sha256').update(value).digest('hex');
const original=await readFile('.local-data/factory.json','utf8'),source=JSON.parse(original),digest=sha(original);
const counts=Object.fromEntries(['machine','report','action','settings'].map(kind=>[kind,Object.keys(source.records).filter(id=>id.startsWith(kind+':')).length]));
const history=Object.values(source.records).reduce((n,record)=>n+(record.history?.length||0),0);
await mkdir('.local-data/backups',{recursive:true});
const backup='.local-data/backups/factory-before-supabase-'+new Date().toISOString().replaceAll(':','-')+'.json';
await copyFile('.local-data/factory.json',backup,constants.COPYFILE_EXCL);
console.log(JSON.stringify({phase:'local-backup',counts,history}));
const current=await cloud.readCloudJson('workspace.json');
if(current&&!isDeepStrictEqual(await cloud.decryptPayload(current.payload),source))throw new Error('Cloud workspace already contains different data. Nothing overwritten.');
if(!current)await cloud.writeCloudJson('workspace.json',{format:'myc-workspace-json-v1',revision:randomUUID(),updated_at:new Date().toISOString(),payload:await cloud.encryptPayload(source)},false);
const verified=await cloud.readCloudJson('workspace.json');
if(!verified||!isDeepStrictEqual(await cloud.decryptPayload(verified.payload),source))throw new Error('Full JSON verification failed.');
console.log(JSON.stringify({phase:'remote-workspace-verified',records:Object.keys(source.records).length,history}));
const cloudBackup='backups/local-'+digest+'.json';
await cloud.writeCloudJson(cloudBackup,{format:'myc-backup-v1',created_at:new Date().toISOString(),payload:await cloud.encryptPayload(source)},true);
const savedBackup=await cloud.readCloudJson(cloudBackup);
if(!isDeepStrictEqual(await cloud.decryptPayload(savedBackup.payload),source))throw new Error('Cloud backup verification failed.');
if(sha(await readFile('.local-data/factory.json','utf8'))!==digest)throw new Error('Local records changed during migration; local mode kept.');
const result={status:'verified',completedAt:new Date().toISOString(),bucket:cloud.cloudBucket,namespace:process.env.MYC_STORAGE_NAMESPACE,file:'workspace.json',format:'workspace-json-v1',records:Object.keys(source.records).length,history,counts,localBackup:backup,cloudBackup,sourceSha256:digest};
await cloud.writeCloudJson('migration.json',result,true);
await writeFile('.local-data/supabase-migration.json',JSON.stringify(result,null,2)+'\n');
let env=await readFile('.env.local','utf8');
env=env.replace(/^MYC_STORAGE=.*$/m,'MYC_STORAGE="supabase"');
env=env.replace(/^MYC_STORAGE_FORMAT=.*\n?/m,'');
env+='MYC_STORAGE_FORMAT="workspace-json-v1"\n';
await writeFile('.env.local.next',env);await rename('.env.local.next','.env.local');
console.log(JSON.stringify({...result,storageActivated:'supabase'}));
